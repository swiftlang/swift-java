import SwiftJava

/// A Swift error that knows how to turn itself into a dedicated Java exception.
///
/// Conformances are generated by jextract.
public protocol _JNIThrowableError: Error {
  func _makeJavaThrowable(in environment: JNIEnvironment) -> jthrowable?
}

extension JNIEnvironment {
  /// Convert the given Swift error into a Java `Throwable`.
  ///
  /// - A Java `Throwable` is passed through as is.
  /// - A ``_JNIThrowableError`` is converted to its dedicated Java exception class.
  /// - Any other error is boxed in a `SwiftErrorException`.
  public func makeJavaThrowable(for error: any Error) -> jthrowable? {
    // If we're throwing something that's already a Java Throwable object,
    // use it directly.
    if let javaObject = error as? any AnyJavaObject,
      let throwable = javaObject.as(Throwable.self)
    {
      return throwable.javaThis
    }

    if let throwableError = error as? any _JNIThrowableError {
      return throwableError._makeJavaThrowable(in: self)
    }
    return makeSwiftErrorException(for: error)
  }

  /// Completes a Java future exceptionally from an async JNI thunk.
  ///
  /// `Future.get()` surfaces failure as `java.util.concurrent.ExecutionException`.
  /// The throwable the Java caller completed with is that exception's cause.
  /// Passing the wrapper itself to `completeExceptionally` makes the outer
  /// future's cause a generic wrapper instead of the original exception
  /// (swift-java issue #915). One `ExecutionException` layer is removed when
  /// its cause is non-null. Every other error uses ``makeJavaThrowable(for:)``.
  public func completeFutureExceptionally(
    _ error: any Error,
    future: jobject?,
    method: jmethodID
  ) {
    let failure = asyncFailureThrowable(for: error)
    _ = interface.CallBooleanMethodA(self, future, method, [jvalue(l: failure.throwable)])
    if failure.deleteLocalRef, let throwable = failure.throwable {
      interface.DeleteLocalRef(self, throwable)
    }
  }

  /// The throwable to pass to `completeExceptionally`, plus whether it is a
  /// local ref this function allocated and must delete after the JNI call.
  private func asyncFailureThrowable(
    for error: any Error
  ) -> (throwable: jthrowable?, deleteLocalRef: Bool) {
    if let javaObject = error as? any AnyJavaObject,
      let throwable = javaObject.as(Throwable.self),
      interface.IsInstanceOf(self, throwable.javaThis, _JNIMethodIDCache.ExecutionException.class) == JNI_TRUE,
      let cause = interface.CallObjectMethodA(
        self,
        throwable.javaThis,
        _JNIMethodIDCache.ExecutionException.getCause,
        nil
      )
    {
      return (cause, true)
    }
    return (makeJavaThrowable(for: error), false)
  }

  /// Throw the given Swift error as a Java exception.
  public func throwSwiftErrorAsJava(_ error: any Error) {
    guard let throwable = makeJavaThrowable(for: error) else {
      return
    }
    _ = interface.Throw(self, throwable)
  }

  /// Box the error in a `SwiftErrorException`.
  private func makeSwiftErrorException(for error: any Error) -> jthrowable? {
    let selfPointer$ = UnsafeMutablePointer<any Error>.allocate(capacity: 1)
    selfPointer$.initialize(to: error)
    let selfPointerBits$ = Int64(Int(bitPattern: selfPointer$))
    let metadata$ = unsafeBitCast((any Error).self, to: UnsafeRawPointer.self)
    let metadataBits$ = Int64(Int(bitPattern: metadata$))
    var args = [jvalue(), jvalue()]
    args[0].j = selfPointerBits$.getJNIValue(in: self)
    args[1].j = metadataBits$.getJNIValue(in: self)
    return interface.CallStaticObjectMethodA(
      self,
      _JNIMethodIDCache.SwiftErrorException.class,
      _JNIMethodIDCache.SwiftErrorException.wrapMemoryAddressUnsafe,
      &args
    )
  }
}
